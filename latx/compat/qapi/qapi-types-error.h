#ifndef LATX_BARE_QAPI_TYPES_ERROR_H
#define LATX_BARE_QAPI_TYPES_ERROR_H
/* The bare build has no QAPI-generated schema; only the error class enum is
 * referenced by the copied QEMU helpers. */
typedef enum QapiErrorClass {
    QAPI_ERROR_CLASS_GENERIC_ERROR = 0,
    QAPI_ERROR_CLASS_COMMAND_NOT_FOUND = 1,
    QAPI_ERROR_CLASS_DEVICE_NOT_ACTIVE = 2,
    QAPI_ERROR_CLASS_DEVICE_NOT_FOUND = 3,
    QAPI_ERROR_CLASS_KVM_MISSING_CAP = 4,
} QapiErrorClass;
#define QAPI_ERROR_CLASS_GENERICERROR        QAPI_ERROR_CLASS_GENERIC_ERROR
#define QAPI_ERROR_CLASS_COMMANDNOTFOUND     QAPI_ERROR_CLASS_COMMAND_NOT_FOUND
#define QAPI_ERROR_CLASS_DEVICENOTACTIVE     QAPI_ERROR_CLASS_DEVICE_NOT_ACTIVE
#define QAPI_ERROR_CLASS_DEVICENOTFOUND      QAPI_ERROR_CLASS_DEVICE_NOT_FOUND
#define QAPI_ERROR_CLASS_KVMMISSINGCAP       QAPI_ERROR_CLASS_KVM_MISSING_CAP
#endif
