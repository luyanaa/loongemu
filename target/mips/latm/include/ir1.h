typedef struct MipsIR1 {
    MIPS_OP op;
    uint32_t insn;
    uint64_t pc;
    uint8_t rs, rt, rd, sa, sel, fmt, cond, aux;
    uint16_t subop;
    int16_t simm;
    uint32_t target;
    bool likely;
    bool link;
    bool delay_slot;
} MipsIR1;

static inline void mips_ir1_init(MipsIR1 *ir1, uint32_t insn, uint64_t pc)
{
    ir1->op = MIPS_OP_NONE;
    ir1->insn = insn;
    ir1->pc = pc;
    ir1->rs = (insn >> 21) & 0x1f;
    ir1->rt = (insn >> 16) & 0x1f;
    ir1->rd = (insn >> 11) & 0x1f;
    ir1->sa = (insn >> 6) & 0x1f;
    ir1->sel = insn & 0x7;
    ir1->fmt = 0;
    ir1->cond = 0;
    ir1->aux = 0;
    ir1->subop = 0;
    ir1->simm = (int16_t)insn;
    ir1->target = insn & 0x03ffffff;
    ir1->likely = false;
    ir1->link = false;
    ir1->delay_slot = false;
}

bool mips_decode_one(MipsIR1 *ir1, uint32_t insn, uint64_t pc);
bool mips_ir1_is_branch(const MipsIR1 *ir1);

