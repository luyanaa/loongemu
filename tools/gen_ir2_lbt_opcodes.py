#!/usr/bin/env python3
"""Generate the LBT-opcode classifier from ir2-opcode.h.

The LATA port can be built with the software NZCV path (LATA_FORCE_NO_LBT=1),
and such an image must not contain a single LoongArch binary-translation
extension instruction: a distro qemu does not decode them and the guest dies with
no diagnostic. The classifier below is the assertion's only dependency, so it is
generated from the enum rather than maintained by hand - the first version of
this check would have been a 143-case list nobody updates.

Regenerate (and commit the result) whenever ir2-opcode.h gains or renames an
LBT instruction:

    python3 tools/gen_ir2_lbt_opcodes.py
"""
import re
import sys

SRC = "shared/backend/loongarch/include/ir2-opcode.h"
DST = "shared/backend/loongarch/include/ir2-lbt-opcodes.h"

# Every LBT mnemonic family in the enum: the ARM-flavoured and x86-flavoured
# instruction sets, plus the scratch-register transfer and jump forms.
PREFIXES = ("LISA_ARM", "LISA_X86")
EXACT = ("LISA_GR2SCR", "LISA_SCR2GR", "LISA_JISCR0", "LISA_JISCR1",
         "LISA_SETARMJ")


def lbt_names(path):
    src = open(path).read()
    names = []
    for line in src.splitlines():
        line = line.split("/*")[0]
        m = re.match(r"\s*(LISA_[A-Z0-9_]+)\s*[,=]", line)
        if not m:
            continue
        name = m.group(1)
        if name.startswith(PREFIXES) or name in EXACT:
            names.append(name)
    return names


def render(names):
    out = []
    out.append("/* Generated by tools/gen_ir2_lbt_opcodes.py - do not edit.")
    out.append(" *")
    out.append(" * ir2_opcode_is_lbt() answers whether an IR2 opcode belongs to the")
    out.append(" * LoongArch binary-translation extension. A software-path image must emit")
    out.append(" * none of them: qemu does not decode LBT, so one leaked instruction turns")
    out.append(" * into a silent guest death instead of a test failure.")
    out.append(" */")
    out.append("#ifndef LOONGEMU_IR2_LBT_OPCODES_H")
    out.append("#define LOONGEMU_IR2_LBT_OPCODES_H")
    out.append("")
    out.append('/* ir2-opcode.h is an enum body; la-ir2.h is what wraps it. */')
    out.append('#include "la-ir2.h"')
    out.append("")
    out.append("static inline int ir2_opcode_is_lbt(int opcode)")
    out.append("{")
    out.append("\t/* clang-format off */")
    out.append("\tswitch (opcode) {")
    for name in names:
        out.append("\tcase %s:" % name)
    out.append("\t\treturn 1;")
    out.append("\tdefault:")
    out.append("\t\treturn 0;")
    out.append("\t}")
    out.append("\t/* clang-format on */")
    out.append("}")
    out.append("")
    out.append("#define IR2_LBT_OPCODE_COUNT %du" % len(names))
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    names = lbt_names(SRC)
    if not names:
        print("no LBT opcodes found in %s" % SRC, file=sys.stderr)
        return 1
    text = render(names)
    try:
        old = open(DST).read()
    except OSError:
        old = None
    if old != text:
        open(DST, "w").write(text)
    print("%s: %d LBT opcodes%s" % (DST, len(names),
                                    "" if old == text else " (updated)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
