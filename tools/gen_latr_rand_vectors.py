#!/usr/bin/env python3
"""Generate the LATR random-instruction differential vectors.

One deterministic program, executed on two engines:

  * LATR: the words are handed to the ISA harness, which translates them and
    runs the emitted LoongArch;
  * QEMU: the same words are emitted as assembly in `latr_rand_run` and executed
    natively by qemu-system-riscv64.

Both compute the same 64-bit hash of x5..x31 afterwards, so a divergence is a
translator defect rather than a known-answer mismatch. The seed is fixed, so the
program is stable across runs and machines; changing the seed changes the whole
case, which is the point of the exercise.

Only non-trapping R-type integer ops are used: no loads, stores, branches, CSRs
or vector state, so both sides run without a trap handler. Division by zero and
INT_MIN / -1 are *included* on purpose - RISC-V defines both, and they are the
cases a hand-written test forgets.
"""
import os
import pathlib
import random

# Fixed by default so the program is stable across runs and machines. Override
# with LATR_RAND_SEED=<n> to widen coverage locally (a differing seed is how a
# translator bug hiding behind one particular stream gets found).
SEED = int(os.environ.get("LATR_RAND_SEED", "0x5EED1A7D"), 0)
COUNT = 48
FILLER = 32  # instructions QEMU executes before the stream (not part of the diff)

# name -> (opcode, funct3, funct7)
R_OPS = {
    "add":   (0x33, 0, 0x00), "sub":   (0x33, 0, 0x20),
    "sll":   (0x33, 1, 0x00), "slt":   (0x33, 2, 0x00),
    "sltu":  (0x33, 3, 0x00), "xor":   (0x33, 4, 0x00),
    "srl":   (0x33, 5, 0x00), "sra":   (0x33, 5, 0x20),
    "or":    (0x33, 6, 0x00), "and":   (0x33, 7, 0x00),
    "mul":   (0x33, 0, 0x01), "mulh":  (0x33, 1, 0x01),
    "mulhsu": (0x33, 2, 0x01), "mulhu": (0x33, 3, 0x01),
    "div":   (0x33, 4, 0x01), "divu":  (0x33, 5, 0x01),
    "rem":   (0x33, 6, 0x01), "remu":  (0x33, 7, 0x01),
    "addw":  (0x3B, 0, 0x00), "subw":  (0x3B, 0, 0x20),
    "sllw":  (0x3B, 1, 0x00), "srlw":  (0x3B, 5, 0x00),
    "sraw":  (0x3B, 5, 0x20), "mulw":  (0x3B, 0, 0x01),
    "divw":  (0x3B, 4, 0x01), "divuw": (0x3B, 5, 0x01),
    "remw":  (0x3B, 6, 0x01), "remuw": (0x3B, 7, 0x01),
}

HASH_SEED = 0x9E3779B97F4A7C15
HASH_PRIME = 0x100000001B3


def encode_r(op, rd, rs1, rs2):
    opcode, funct3, funct7 = R_OPS[op]
    # funct3 sits in bits 14:12; shifting it by 11 corrupts rd's high bits and
    # produces encodings that are illegal for the opcode (found by the
    # differential: QEMU trapped on one of them).
    return ((funct7 << 25) | (rs2 << 20) | (rs1 << 15) | (funct3 << 12) |
            (rd << 7) | opcode)


def main():
    rng = random.Random(SEED)
    ops = sorted(R_OPS)
    words = []
    for _ in range(COUNT):
        op = rng.choice(ops)
        rd = rng.randrange(5, 32)
        rs1 = rng.randrange(5, 32)
        rs2 = rng.randrange(5, 32)
        words.append(encode_r(op, rd, rs1, rs2))

    # Interesting starting values are mixed with random ones: 0, -1, INT_MIN,
    # INT_MAX, powers of two and the divisor extremes.
    special = [0, 1, 0xFFFFFFFFFFFFFFFF, 0x7FFFFFFFFFFFFFFF,
               0x8000000000000000, 0xFFFFFFFF, 0x7FFFFFFF,
               0x80000000, 0xFFFFFFFF80000000]
    init = []
    for i in range(27):
        if i < len(special):
            init.append(special[i])
        else:
            init.append(rng.getrandbits(64))

    out = pathlib.Path("build")
    out.mkdir(parents=True, exist_ok=True)

    header = ["/* Generated by tools/gen_latr_rand_vectors.py - do not edit. */",
              "#ifndef LATR_RAND_VECTORS_H",
              "#define LATR_RAND_VECTORS_H",
              "",
              "#define LATR_RAND_COUNT %du" % COUNT,
              "#define LATR_RAND_REGS 27u",
              "",
              "static const uint32_t latr_rand_words[LATR_RAND_COUNT] = {"]
    for w in words:
        header.append("    0x%08xu," % w)
    header.append("};")
    header.append("")
    header.append("/* Initial x5..x31. */")
    header.append("static const uint64_t latr_rand_init[LATR_RAND_REGS] = {")
    for v in init:
        header.append("    UINT64_C(0x%016x)," % v)
    header.append("};")
    header.append("")
    header.append("#define LATR_RAND_HASH_SEED UINT64_C(0x%016x)" % HASH_SEED)
    header.append("#define LATR_RAND_HASH_PRIME UINT64_C(0x%016x)" % HASH_PRIME)
    header.append("")
    header.append("#endif")
    (out / "latr_rand_vectors.h").write_text("\n".join(header) + "\n")

    # Assembly half: latr_rand_run loads the same seeds, executes the same words
    # and returns the same hash in a0. x3 holds the return address (x1 is the
    # hash accumulator) and x4 the table pointer; both are outside x5..x31 and
    # outside the stream's register set.
    asm = ["/* Generated by tools/gen_latr_rand_vectors.py - do not edit. */",
           "    .section .text",
           "    .globl latr_rand_run",
           "    .type latr_rand_run, @function",
           "latr_rand_run:",
           "    mv      x3, ra",
           "    la      x4, .Lrand_init"]
    for i in range(27):
        asm.append("    ld      x%u, %u(x4)" % (5 + i, 8 * i))
    for w in words:
        asm.append("    .word   0x%08x" % w)
    asm += ["    li      x1, 0x%x" % HASH_SEED,
            "    li      x2, 0x%x" % HASH_PRIME]
    for i in range(27):
        asm.append("    xor     x1, x1, x%u" % (5 + i))
        asm.append("    mul     x1, x1, x2")
    asm += ["    mv      a0, x1",
            "    mv      ra, x3",
            "    ret",
            "    .section .rodata",
            "    .align 3",
            ".Lrand_init:"]
    for v in init:
        asm.append("    .dword  0x%016x" % v)
    asm.append("    .text")
    (out / "latr_rand_run.inc").write_text("\n".join(asm) + "\n")


if __name__ == "__main__":
    main()
