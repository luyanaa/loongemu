#!/usr/bin/env python3
"""Generate helper_* prototypes from a QEMU DEF_HELPER list.

QEMU normally generates exec/helper-proto.h at build time from the
DEF_HELPER_* macros in target/i386/helper.h.  The bare build has no such
generator step, so this reproduces it: one prototype per macro, with the
QEMU type aliases expanded to concrete C types.
"""
import re
import sys

TYPE = {
    "env": "CPUArchState *env",
    "i32": "uint32_t",
    "i64": "uint64_t",
    "tl": "target_ulong",
    "ptr": "void *",
    "f32": "float32",
    "f64": "float64",
    "s32": "int32_t",
    "s64": "int64_t",
    "int": "int",
    "void": "void",
}

def split_args(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

src = open(sys.argv[1]).read() if len(sys.argv) > 1 else sys.stdin.read()
pat = re.compile(r"DEF_HELPER(_FLAGS)?_(\d)\(\s*([A-Za-z0-9_]+)\s*,([^;]*?)\)\s*$", re.M)
seen = set()
lines = []
for m in pat.finditer(src):
    is_flags = bool(m.group(1))
    n = int(m.group(2))
    name = m.group(3)
    rest = split_args(m.group(4))
    if is_flags:
        rest = rest[1:]          # drop the TCG_CALL_* flag word
    if len(rest) < n + 1:
        continue
    ret = TYPE.get(rest[0], rest[0])
    args = [TYPE.get(a, a) for a in rest[1:n + 1]]
    if name in seen:
        continue
    seen.add(name)
    proto = "%s helper_%s(%s);" % (ret, name, ", ".join(args) if args else "void")
    lines.append(proto)

print("/* generated by tools/latx_bare/gen_helper_proto.py from helper.h */")
print("#ifndef LATX_HELPER_PROTO_GENERATED_H")
print("#define LATX_HELPER_PROTO_GENERATED_H")
print('#include "qemu/osdep.h"')
print('#include "cpu.h"')
print('#ifndef HELPER')
print('#define HELPER(x) glue(helper_, x)')
print('#endif')
for line in lines:
    print(line)
print("#endif")
